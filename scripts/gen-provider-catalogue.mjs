#!/usr/bin/env node
// gen-provider-catalogue.mjs — regenerate providers/catalogue-snapshot.ts from models.dev.
//
// This is the offline floor for provider *identity* (id, name, SDK package,
// baseURL, env var names). It exists so a first run with no disk cache and no
// network still knows how to construct a provider — the same job opencode's
// build-time `OPENCODE_MODELS_DEV` define does (packages/cli/script/build.ts).
//
// A generated .ts file rather than a JSON asset or a bundler `--define`:
// freecode builds three ways (tsx in dev, `tsc` for the npm package,
// `bun build --compile` for the release binary) and a plain .ts import is the
// only form all three handle with no extra plumbing.
//
// Deliberately provider-level only. Model lists and per-model limits are the
// large, fast-moving part of models.dev and are already fetched at runtime by
// apps/core/src/models-dev.ts — duplicating them here would be a second stale
// copy of the exact data that file exists to keep fresh.
//
// Run: pnpm gen:catalogue          — rewrite the snapshot
//      pnpm gen:catalogue --check  — exit 1 if it is out of date, write nothing
//
// The --check mode is what a scheduled workflow runs: provider identity drifts
// on models.dev whether or not anyone regenerates, and a snapshot nobody
// refreshes silently becomes a list of the providers that existed the day it
// was generated.

import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const SOURCE = process.env.FREECODE_MODELS_URL || "https://models.dev/api.json";
const OUT = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
  "apps",
  "core",
  "src",
  "providers",
  "catalogue-snapshot.ts",
);

const res = await fetch(SOURCE, { signal: AbortSignal.timeout(30_000) });
if (!res.ok) {
  console.error(`gen-provider-catalogue: ${SOURCE} returned ${res.status}`);
  process.exit(1);
}
const raw = await res.json();

const entries = [];
for (const [id, p] of Object.entries(raw)) {
  // No npm package means nothing here can construct it, so it would be dead
  // weight in the snapshot regardless of whether an SDK factory exists today.
  if (!p || typeof p !== "object" || !p.npm) continue;
  entries.push({
    id,
    name: p.name || id,
    npm: p.npm,
    ...(p.api ? { baseURL: p.api } : {}),
    envKeys: Array.isArray(p.env) ? p.env : [],
  });
}
entries.sort((a, b) => a.id.localeCompare(b.id));

if (entries.length === 0) {
  console.error("gen-provider-catalogue: refusing to write an empty snapshot");
  process.exit(1);
}

const body = entries
  .map((e) => `  ${JSON.stringify(e)},`)
  .join("\n");

const contents = `// GENERATED by scripts/gen-provider-catalogue.mjs — do not edit by hand.
// Source: ${SOURCE}
// Generated: ${new Date().toISOString().slice(0, 10)}
//
// Provider identity only (id, name, SDK package, baseURL, env var names).
// Model lists and limits are fetched at runtime by models-dev.ts. Regenerate
// with \`pnpm gen:catalogue\`.
import type { SnapshotEntry } from "./catalogue-types.js";

export const CATALOGUE_SNAPSHOT: SnapshotEntry[] = [
${body}
];
`;

// The generated header carries a date, so comparing whole files would report
// drift every single day. Only the provider rows matter.
const rows = (text) =>
  text
    .split("\n")
    .filter((line) => line.startsWith("  {"))
    .join("\n");

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf-8") : "";
  if (rows(current) === rows(contents)) {
    console.log(`gen-provider-catalogue: up to date (${entries.length} providers)`);
    process.exit(0);
  }
  console.error(
    "gen-provider-catalogue: snapshot is out of date — run `pnpm gen:catalogue`",
  );
  process.exit(1);
}

writeFileSync(OUT, contents, "utf-8");

console.log(
  `gen-provider-catalogue: wrote ${entries.length} providers to ${path.relative(process.cwd(), OUT)}`,
);
